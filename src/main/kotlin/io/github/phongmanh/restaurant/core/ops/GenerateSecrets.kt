package io.github.phongmanh.restaurant.core.ops

import java.io.File
import java.io.PrintStream
import java.math.BigInteger
import java.nio.file.Files
import java.nio.file.attribute.PosixFilePermissions
import java.security.KeyPair
import java.security.KeyPairGenerator
import java.security.SecureRandom
import java.security.interfaces.ECPrivateKey
import java.security.interfaces.ECPublicKey
import java.security.spec.ECGenParameterSpec
import java.util.Base64
import kotlin.system.exitProcess

/**
 * Makes a new environment's secrets (core-and-auth §8, §13) and writes them to an env file that git
 * ignores, so no secret passes through a terminal or a chat:
 *
 * `./gradlew generateSecrets --args="deploy/staging/.env.staging --db-host ep-….ap-southeast-1.aws.neon.tech --db-name restaurant"`
 *
 * `--db-host` is the database's **pooled** host: the `app` and `app_platform` URLs go through the
 * pooler (ADR-0004), and `./gradlew migrate` creates both roles with the passwords made here. The
 * secrets that come from a provider (the migrator's direct URL, Upstash, Ably) are written as empty
 * lines for the operator to fill. The file is never overwritten, so a second run can't rotate keys by
 * accident, and only the names are printed.
 */
fun main(args: Array<String>) {
    exitProcess(runGenerateSecrets(args.toList(), System.out))
}

/** Writes the file; returns the exit code. */
fun runGenerateSecrets(
    args: List<String>,
    out: PrintStream,
): Int {
    val path = args.firstOrNull()?.takeUnless { it.startsWith("--") }
    val options =
        args
            .drop(1)
            .chunked(2)
            .filter { it.size == 2 }
            .associate { (k, v) -> k to v }
    val host = options["--db-host"]?.takeIf(HOST::matches)
    val dbName = options["--db-name"] ?: "restaurant"
    val file = path?.let(::File)
    return when {
        file == null || host == null || !NAME.matches(dbName) -> 2.also { out.println(USAGE) }
        file.exists() -> 1.also { out.println("$path exists; it's never overwritten. Move it away first if you mean to make new secrets.") }
        else -> 0.also { write(file, generate(host, dbName), out) }
    }
}

private fun write(
    file: File,
    values: Map<String, String>,
    out: PrintStream,
) {
    file.absoluteFile.parentFile.mkdirs()
    Files.createFile(file.toPath(), PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------")))
    file.writeText(
        buildString {
            appendLine("# Generated by ./gradlew generateSecrets. Never commit, print or paste this file.")
            values.forEach { (name, value) -> appendLine("$name=$value") }
            appendLine("# Fill these from the providers' consoles:")
            PROVIDED.forEach { appendLine("$it=") }
        },
    )
    out.println("Wrote ${file.path} with ${values.keys.joinToString()}.")
    out.println("Fill in ${PROVIDED.joinToString()}.")
}

/** The generated values, in file order. */
internal fun generate(
    host: String,
    dbName: String,
): Map<String, String> =
    linkedMapOf(
        "DATABASE_URL" to "postgresql://app:${token(PASSWORD_BYTES)}@$host/$dbName?sslmode=require",
        "DATABASE_URL_PLATFORM" to "postgresql://app_platform:${token(PASSWORD_BYTES)}@$host/$dbName?sslmode=require",
        "STAFF_JWT_KEYS" to keySet("staff-1"),
        "GUEST_JWT_KEYS" to keySet("guest-1"),
        // A printed QR code carries its key ID in one byte (tables §2), so the IDs are numbers.
        "QR_SIGNING_KEYS" to keySet("1"),
        "TOTP_ENCRYPTION_KEYS" to """{"current":"t1","keys":{"t1":"${Base64.getEncoder().encodeToString(bytes(KEY_BYTES))}"}}""",
        "EMAIL_HMAC_KEY" to Base64.getEncoder().encodeToString(bytes(KEY_BYTES)),
        "CRON_SECRET" to token(KEY_BYTES),
    )

/** The secrets a provider issues; the file gets an empty line for each. */
internal val PROVIDED =
    listOf(
        "DATABASE_URL_MIGRATOR_DIRECT",
        "UPSTASH_REDIS_REST_URL",
        "UPSTASH_REDIS_REST_TOKEN",
        "ABLY_API_KEY",
        "VERCEL_AUTOMATION_BYPASS_SECRET",
    )

private val random = SecureRandom()

private fun bytes(n: Int) = ByteArray(n).also(random::nextBytes)

/** URL-safe, so it can sit in a connection URL without escaping. */
private fun token(n: Int) = Base64.getUrlEncoder().withoutPadding().encodeToString(bytes(n))

/** A JWK set with one P-256 signing key, in the format `EcKeySet.parse` reads. */
private fun keySet(kid: String): String {
    val pair: KeyPair = KeyPairGenerator.getInstance("EC").apply { initialize(ECGenParameterSpec("secp256r1"), random) }.generateKeyPair()
    val pub = pair.public as ECPublicKey
    val d = (pair.private as ECPrivateKey).s
    return """{"keys":[{"kty":"EC","crv":"P-256","kid":"$kid","x":"${b64(pub.w.affineX)}","y":"${b64(pub.w.affineY)}","d":"${b64(d)}"}]}"""
}

private fun b64(n: BigInteger): String {
    val bytes =
        n.toByteArray().let {
            if (it.size >
                KEY_BYTES
            ) {
                it.copyOfRange(it.size - KEY_BYTES, it.size)
            } else {
                ByteArray(KEY_BYTES - it.size) + it
            }
        }
    return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes)
}

/** 256 bits: the AES, HMAC and cron keys, and a P-256 coordinate. */
private const val KEY_BYTES = 32

/** 192 bits, 32 characters once encoded. */
private const val PASSWORD_BYTES = 24

private val HOST = Regex("[A-Za-z0-9.-]+")
private val NAME = Regex("[A-Za-z0-9_]+")

private const val USAGE = "usage: generateSecrets --args=\"<file> --db-host <pooled database host> [--db-name <database>]\""
